"""
Training Script for Temporal Framework Data

Trains Random Forest model on data generated by aggregate_30min_temporal.py
Ensures proper temporal framework: Observation (30min) -> Lag (10min) -> Prediction (10min)
"""

import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error
import sys
import os

sys.path.append(os.path.dirname(os.path.abspath(__file__)))

from database.mongodb import MongoManager
from config import config

# Feature lists
SENTIMENT_FEATURES = [
    'llm_sentiment_avg',
    'llm_confidence_avg'
]

NLP_FEATURES = [
    'avg_positive_word_ratio',
    'avg_negative_word_ratio',
    'avg_compound_score',
    'total_avg_sentence_length',
    'total_word_count',
    'avg_unique_word_ratio',
    'total_exclamation_count',
    'total_question_count',
    'num_articles',  # From aggregation root
    'total_btc_mention_count',
    'total_price_keyword_count',
    'avg_technical_term_ratio',
    'total_ne_person_count',
    'total_ne_org_count'
]

def load_temporal_data():
    """
    Load data from temporal aggregation collection.
    
    Returns:
        DataFrame with proper temporal structure
    """
    print("🔗 Connecting to MongoDB...")
    conn_str = config.MONGODB_CONNECTION_STRING
    if "@mongodb" in conn_str:
        conn_str = conn_str.replace("@mongodb", "@localhost")
    
    mongo = MongoManager('blog-data', uri=conn_str)
    
    print("📊 Loading temporal aggregation data...")
    records = list(mongo.find('aggregated_features_temporal'))
    
    if not records:
        print("❌ No data found in 'aggregated_features_temporal' collection")
        print("   Run: python3 aggregate_30min_temporal.py")
        return None
    
    print(f"✅ Loaded {len(records)} temporal windows")
    
    # Flatten structure
    data = []
    for r in records:
        # Verify temporal framework
        assert 'observation_window' in r, "Missing observation_window"
        assert 'lag_window' in r, "Missing lag_window"
        assert 'prediction_window' in r, "Missing prediction_window"
        
        # Verify temporal ordering
        obs_end = r['observation_window']['end']
        lag_start = r['lag_window']['start']
        lag_end = r['lag_window']['end']
        pred_start = r['prediction_window']['start']
        
        assert obs_end == lag_start, "Observation must end when lag starts"
        assert lag_end == pred_start, "Lag must end when prediction starts"
        
        # Build record
        record = {
            'window_start': r['window_start'],
            'num_articles': r.get('num_articles', 0),
            'llm_sentiment_avg': r.get('llm_sentiment_avg', 0),
            'llm_confidence_avg': r.get('llm_confidence_avg', 0)
        }
        
        # Add NLP features
        nlp_agg = r.get('nlp_features_agg', {})
        for feat in NLP_FEATURES:
            if feat == 'num_articles':
                continue  # Already added
            record[feat] = nlp_agg.get(feat, 0)
        
        # Target (with proper temporal lag)
        if r.get('labeled'):
            record['target_lagged'] = r['price_movement_lagged']
        else:
            record['target_lagged'] = None
        
        data.append(record)
    
    df = pd.DataFrame(data)
    
    # Drop rows without labels
    df = df.dropna(subset=['target_lagged'])
    
    print(f"📈 Final dataset: {len(df)} labeled samples")
    print(f"   Observation window: 30 minutes")
    print(f"   Lag period: 10 minutes")
    print(f"   Prediction window: 10 minutes")
    print(f"   Total temporal span: 50 minutes per sample")
    
    return df

def prepare_features(df):
    """Prepare feature matrix and target vector."""
    # All features
    all_features = SENTIMENT_FEATURES + [f for f in NLP_FEATURES if f != 'num_articles'] + ['num_articles']
    
    # Filter to existing columns
    available_features = [f for f in all_features if f in df.columns]
    
    print(f"\n📋 Features: {len(available_features)}")
    print(f"   Sentiment: {len(SENTIMENT_FEATURES)}")
    print(f"   NLP: {len([f for f in NLP_FEATURES if f in df.columns])}")
    
    X = df[available_features].fillna(0)
    y = df['target_lagged'].values
    
    return X, y, available_features

def train_temporal_model(df):
    """
    Train Random Forest on temporal data.
    
    Args:
        df: DataFrame from load_temporal_data()
        
    Returns:
        dict: Training results
    """
    print("\n" + "="*70)
    print("🤖 TRAINING RANDOM FOREST WITH TEMPORAL FRAMEWORK")
    print("="*70)
    
    # Sort by time (mandatory for temporal split)
    df = df.sort_values('window_start').reset_index(drop=True)
    
    # Prepare features
    X, y, features = prepare_features(df)
    
    # Temporal split (70/15/15)
    n = len(df)
    train_size = int(n * 0.70)
    val_size = int(n * 0.15)
    
    train_idx = slice(0, train_size)
    val_idx = slice(train_size, train_size + val_size)
    test_idx = slice(train_size + val_size, n)
    
    X_train, y_train = X.iloc[train_idx], y[train_idx]
    X_val, y_val = X.iloc[val_idx], y[val_idx]
    X_test, y_test = X.iloc[test_idx], y[test_idx]
    
    print(f"\n📊 Dataset Split:")
    print(f"   Training: {len(X_train)} samples")
    print(f"   Validation: {len(X_val)} samples")
    print(f"   Test: {len(X_test)} samples")
    
    # Scale features
    scaler = MinMaxScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_val_scaled = scaler.transform(X_val)
    X_test_scaled = scaler.transform(X_test)
    
    # Add Gaussian noise (regularization)
    noise_std = 0.05
    noise = np.random.normal(0, noise_std * X_train_scaled.std(axis=0), X_train_scaled.shape)
    X_train_noisy = X_train_scaled + noise
    
    print(f"\n⚙️  Model Configuration:")
    print(f"   Algorithm: Random Forest")
    print(f"   n_estimators: 100")
    print(f"   max_depth: 5")
    print(f"   min_samples_split: 10")
    print(f"   min_samples_leaf: 5")
    print(f"   Regularization: Gaussian noise (std={noise_std})")
    
    # Train model
    model = RandomForestRegressor(
        n_estimators=100,
        max_depth=5,
        min_samples_split=10,
        min_samples_leaf=5,
        max_features='sqrt',
        random_state=42,
        n_jobs=-1
    )
    
    print("\n🔄 Training...")
    model.fit(X_train_noisy, y_train)
    
    # Evaluate
    y_train_pred = model.predict(X_train_scaled)
    y_val_pred = model.predict(X_val_scaled)
    y_test_pred = model.predict(X_test_scaled)
    
    results = {
        'train': {
            'r2': r2_score(y_train, y_train_pred),
            'mae': mean_absolute_error(y_train, y_train_pred),
            'mse': mean_squared_error(y_train, y_train_pred)
        },
        'val': {
            'r2': r2_score(y_val, y_val_pred),
            'mae': mean_absolute_error(y_val, y_val_pred),
            'mse': mean_squared_error(y_val, y_val_pred)
        },
        'test': {
            'r2': r2_score(y_test, y_test_pred),
            'mae': mean_absolute_error(y_test, y_test_pred),
            'mse': mean_squared_error(y_test, y_test_pred)
        }
    }
    
    # Display results
    print("\n" + "="*70)
    print("📊 RESULTS (WITH TEMPORAL LAG)")
    print("="*70)
    
    for split_name, metrics in results.items():
        print(f"\n{split_name.upper()}:")
        print(f"  R² Score: {metrics['r2']:.4f}")
        print(f"  MAE: {metrics['mae']:.4f}")
        print(f"  MSE: {metrics['mse']:.4f}")
    
    # Feature importance
    importances = model.feature_importances_
    feature_importance = sorted(
        zip(features, importances),
        key=lambda x: x[1],
        reverse=True
    )
    
    print("\n📊 Top 10 Features:")
    for feat, imp in feature_importance[:10]:
        print(f"  {feat}: {imp:.4f}")
    
    # Interpretation
    print("\n" + "="*70)
    print("🔍 INTERPRETATION")
    print("="*70)
    
    test_r2 = results['test']['r2']
    
    if test_r2 > 0.7:
        print("✅ High R² maintained with temporal lag!")
        print("   → Sentiment has genuine predictive power")
        print("   → 10-min lag insufficient to break signal")
    elif 0.3 <= test_r2 <= 0.7:
        print("✓ Moderate R² with temporal lag")
        print("   → Sentiment provides value, but weaker than concurrent setup")
        print("   → More realistic for production systems")
    elif 0.1 <= test_r2 < 0.3:
        print("~ Weak R² with temporal lag")
        print("   → Sentiment has marginal predictive value")
        print("   → Still beats baseline (R²≈0) but not production-ready")
    else:
        print("❌ Near-zero R² with temporal lag")
        print("   → Original high R² was likely concurrent correlation")
        print("   → No true predictive power after enforcing lag")
    
    print("\n" + "="*70)
    
    return results

if __name__ == "__main__":
    print("="*70)
    print("🚀 TEMPORAL FRAMEWORK TRAINING")
    print("="*70)
    print("\nThis script trains on data with proper temporal structure:")
    print("  1. Observation Window: 30 minutes (collect news)")
    print("  2. Lag Period: 10 minutes (enforced gap)")
    print("  3. Prediction Window: 10 minutes (target measurement)")
    print("\nEnsures features PRECEDE target by mandatory lag period.\n")
    
    # Load data
    df = load_temporal_data()
    
    if df is None or len(df) == 0:
        print("\n❌ Cannot proceed without temporal data")
        print("   Please run aggregation first:")
        print("   $ python3 aggregate_30min_temporal.py")
        sys.exit(1)
    
    # Train
    results = train_temporal_model(df)
    
    print("\n✅ Training complete!")
    print(f"   Test R²: {results['test']['r2']:.4f}")
    print("\nCompare this with concurrent setup R² = 0.83")
    print("to assess impact of temporal lag on predictive power.")
